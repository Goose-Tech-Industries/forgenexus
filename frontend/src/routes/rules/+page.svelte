  <h1>Community Rules</h1>

  <section>
    <h2>1. Be Respectful</h2>
    <p>Treat all members with respect. No personal attacks, harassment, hate speech, or discrimination of any kind.</p>
  </section>

  <section>
    <h2>2. Stay On Topic</h2>
    <p>Post in the appropriate forum. Keep discussions relevant to the thread topic. Off-topic conversations belong in the designated areas.</p>
  </section>

  <section>
    <h2>3. No Spam</h2>
    <p>No unsolicited advertising, self-promotion, or repetitive posting. One account per person.</p>
  </section>

  <section>
    <h2>4. Keep It Clean</h2>
    <p>No explicit or NSFW content unless in designated areas. Use spoiler tags for sensitive content. Keep language appropriate.</p>
  </section>

  <section>
    <h2>5. No Piracy or Illegal Content</h2>
    <p>Do not share pirated material, illegal downloads, or content that violates copyright. Do not discuss illegal activities.</p>
  </section>

  <section>
    <h2>6. Respect Privacy</h2>
    <p>Do not share other people's personal information. No doxxing, no sharing private messages publicly without consent.</p>
  </section>

  <section>
    <h2>7. Follow Staff Instructions</h2>
    <p>Moderators and administrators enforce these rules. Follow their instructions. If you disagree with a decision, use the appeals system.</p>
  </section>

  <section>
    <h2>Consequences</h2>
    <p>Violations result in warnings (with point values). Points accumulate and trigger automatic sanctions: cooldowns, read-only mode, temporary bans, or permanent bans depending on severity.</p>
  </section>
</div>

